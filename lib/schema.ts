/**
 * Schema is expressed as individual statements so it can run on both drivers:
 * the Neon HTTP driver executes one statement per round-trip.
 *
 * Every statement is idempotent, so `ensureSchema()` can run on each cold start.
 */
export const SCHEMA_STATEMENTS: string[] = [
  `create table if not exists users (
    id text primary key,
    username text not null,
    username_lower text not null unique,
    email text unique,
    password_hash text not null,
    created_at timestamptz not null default now()
  )`,

  `create table if not exists sessions (
    token_hash text primary key,
    user_id text not null references users(id) on delete cascade,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null
  )`,
  `create index if not exists sessions_user_idx on sessions (user_id)`,

  `create table if not exists groups (
    id text primary key,
    name text not null,
    owner_id text references users(id) on delete set null,
    invite_code text not null unique,
    created_at timestamptz not null default now()
  )`,

  `create table if not exists memberships (
    group_id text not null references groups(id) on delete cascade,
    user_id text not null references users(id) on delete cascade,
    role text not null default 'member',
    joined_at timestamptz not null default now(),
    primary key (group_id, user_id)
  )`,
  `create index if not exists memberships_user_idx on memberships (user_id)`,

  `create table if not exists messages (
    seq bigint generated by default as identity primary key,
    id text not null unique,
    group_id text not null references groups(id) on delete cascade,
    author_id text references users(id) on delete set null,
    kind text not null default 'user',
    body text not null,
    created_at timestamptz not null
  )`,
  `create index if not exists messages_group_seq_idx on messages (group_id, seq)`,

  `create table if not exists plans (
    group_id text primary key references groups(id) on delete cascade,
    title text not null default 'Party plan',
    event_at timestamptz,
    location_note text not null default '',
    budget_note text not null default '',
    finalized_at timestamptz,
    updated_at timestamptz not null default now()
  )`,

  `create table if not exists venues (
    id text primary key,
    group_id text not null references groups(id) on delete cascade,
    name text not null,
    note text not null default '',
    proposed_by text references users(id) on delete set null,
    created_at timestamptz not null default now()
  )`,
  `create index if not exists venues_group_idx on venues (group_id)`,

  `create table if not exists venue_votes (
    venue_id text not null references venues(id) on delete cascade,
    user_id text not null references users(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (venue_id, user_id)
  )`,

  `create table if not exists rsvps (
    group_id text not null references groups(id) on delete cascade,
    user_id text not null references users(id) on delete cascade,
    status text not null,
    updated_at timestamptz not null default now(),
    primary key (group_id, user_id)
  )`,

  `create table if not exists login_attempts (
    id bigint generated by default as identity primary key,
    username_lower text not null,
    created_at timestamptz not null default now()
  )`,
  `create index if not exists login_attempts_lookup_idx on login_attempts (username_lower, created_at)`,

  `create table if not exists meta (
    key text primary key,
    value text not null
  )`,
];

